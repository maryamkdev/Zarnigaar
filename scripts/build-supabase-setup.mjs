import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const migrations = path.join(root, 'supabase/migrations');
const files = (await readdir(migrations)).filter(name => /^\d+_.*\.sql$/.test(name)).sort();
const existingGuard = `do $fresh_project$
begin
  if exists (
    select 1 from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relname in (
      'profiles', 'admin_users', 'categories', 'collections', 'products',
      'product_images', 'collection_products', 'orders', 'order_items',
      'discounts', 'discount_usages', 'deals', 'wishlists', 'wishlist_items',
      'faqs', 'media', 'contact_messages', 'product_reviews'
    )
  ) then
    raise exception 'Application tables already exist. Use setup/04_product_reviews_update.sql for an existing installation; do not rerun initialization.';
  end if;
end;
$fresh_project$;`;

async function bundle(output, selected, description, fresh) {
  const sections = [
    `-- ${description}`,
    '-- Generated by: node scripts/build-supabase-setup.mjs',
    `-- Includes: ${selected.join(', ')}`,
    '-- Run the ENTIRE file in Supabase SQL Editor as postgres.',
    '-- Supabase CLI migration-history rows are not created by this bundle.',
    'begin;',
    ...(fresh ? [existingGuard] : []),
  ];
  for (const name of selected) {
    sections.push(`-- SOURCE: supabase/migrations/${name}`);
    sections.push((await readFile(path.join(migrations, name), 'utf8')).trimEnd());
  }
  sections.push('commit;');
  await writeFile(path.join(root, output), `${sections.join('\n\n')}\n`);
  console.log(`Generated ${output}`);
}

await bundle('supabase/unified_migrations.sql', files,
  'Zarnigaar: initialize a NEW, EMPTY project, including optional demo inventory. Run once.', true);
await bundle('supabase/setup/01_initialize.sql', files.filter(name => !name.startsWith('0004_')),
  'Zarnigaar: initialize a NEW, EMPTY project without demo inventory. Run once.', true);
await bundle('supabase/setup/04_product_reviews_update.sql', files.filter(name => /^000[89]_/.test(name)),
  'Zarnigaar: upgrade an EXISTING project with migrations 0001-0007 already applied. Cleans original sample fabric claims and enables reviews.', false);
